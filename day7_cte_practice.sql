    CUSTOMER.LASTNAME,
    CUSTOMER.COUNTRY,
    SUM(INVOICE.TOTAL) AS TOTALSPENT
FROM CUSTOMER
JOIN INVOICE ON CUSTOMER.CUSTOMERID = INVOICE.CUSTOMERID
WHERE CUSTOMER.COUNTRY = 'UNITED KINGDOM'
GROUP BY CUSTOMER.CUSTOMERID
ORDER BY TOTALSPENT DESC;

