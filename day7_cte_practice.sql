--YEARLY REVENUE TREND--
WITH YEARLY_REVENUE AS (
    SELECT 
        SUBSTR(INVOICEDATE, 1, 4) AS YEAR,
        SUM(TOTAL) AS REVENUE,
        COUNT(*) AS INVOICECOUNT
    FROM INVOICE
    GROUP BY YEAR
)

SELECT 
    YEAR,
    ROUND(REVENUE, 2) AS REVENUE,
    INVOICECOUNT,
    ROUND(REVENUE / INVOICECOUNT, 2) AS AVGINVOICEVALUE
FROM YEARLY_REVENUE
ORDER BY YEAR;

