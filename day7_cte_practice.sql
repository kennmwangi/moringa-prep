--CUSTOMER SEGMENTATION BY SPENDING--
WITH customer_totals AS (
    SELECT 
        CustomerId,
        SUM(Total) AS LifetimeSpending,
        COUNT(*) AS InvoiceCount
    FROM Invoice
    GROUP BY CustomerId
)

SELECT 
    Customer.FirstName,
    Customer.LastName,
    Customer.Country,
    ROUND(customer_totals.LifetimeSpending, 2) AS LifetimeSpending,
    customer_totals.InvoiceCount,
    CASE 
        WHEN customer_totals.LifetimeSpending >= 40 THEN 'Premium'
        WHEN customer_totals.LifetimeSpending >= 30 THEN 'Regular'
        ELSE 'Casual'
    END AS CustomerSegment
FROM Customer
JOIN customer_totals ON Customer.CustomerId = customer_totals.CustomerId
ORDER BY customer_totals.LifetimeSpending DESC;

