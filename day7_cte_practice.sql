-- Q4: BEST-SELLING ALBUM EACH YEAR--
WITH ALBUM_YEARLY_SALES AS (
    SELECT 
        SUBSTR(INVOICE.INVOICEDATE, 1, 4) AS YEAR,
        ALBUM.TITLE AS ALBUMTITLE,
        ARTIST.NAME AS ARTISTNAME,
        SUM(INVOICELINE.QUANTITY) AS UNITSSOLD
    FROM INVOICELINE
    JOIN TRACK ON INVOICELINE.TRACKID = TRACK.TRACKID
    JOIN ALBUM ON TRACK.ALBUMID = ALBUM.ALBUMID
    JOIN ARTIST ON ALBUM.ARTISTID = ARTIST.ARTISTID
    JOIN INVOICE ON INVOICELINE.INVOICEID = INVOICE.INVOICEID
    GROUP BY YEAR, ALBUM.ALBUMID, ALBUM.TITLE, ARTIST.NAME
),
YEARLY_MAX AS (
    SELECT YEAR, MAX(UNITSSOLD) AS MAXSOLD
    FROM ALBUM_YEARLY_SALES
    GROUP BY YEAR
)

SELECT 
    AYS.YEAR,
    AYS.ALBUMTITLE,
    AYS.ARTISTNAME,
    AYS.UNITSSOLD
FROM ALBUM_YEARLY_SALES AYS
JOIN YEARLY_MAX YM 
    ON AYS.YEAR = YM.YEAR 
    AND AYS.UNITSSOLD = YM.MAXSOLD
ORDER BY AYS.YEAR;

